/********************************** (C) COPYRIGHT *******************************
 * File Name          : boot_info.h
 * Description        : Per-product identity of the bootloader.
 *
 * One bootloader image per product, with the identity, the keys
 * (boot/User/img_key.c) and the build version all compiled in.  Nothing has to
 * be provisioned at run time, so a dumped flash cannot be re-keyed to accept a
 * foreign image.
 *
 * Change these three values (or pass them on the command line, e.g.
 * `sh tools/build.sh boot -DBOOT_PRODUCT_ID=0x0102`) and rebuild; the keys live
 * in img_key.c, generated by `python tools/gen_key.py --write`.
 *
 * They are reported through IAP_CMD_INFO and BOOT_USB_PID, which makes it easy
 * to tell products apart on a production PC.
 *********************************************************************************
 * Copyright (c) 2021 Nanjing Qinheng Microelectronics Co., Ltd.
 * Attention: This software (modified or not) and binary are used for
 * microcontroller manufactured by Nanjing Qinheng Microelectronics.
 *******************************************************************************/
#ifndef __BOOT_INFO_H
#define __BOOT_INFO_H

/* 0x0000 is reserved for development builds */
#ifndef BOOT_PRODUCT_ID
#define BOOT_PRODUCT_ID         0x0000u
#endif

#ifndef BOOT_VERSION_MAJOR
#define BOOT_VERSION_MAJOR      1u
#endif

#ifndef BOOT_VERSION_MINOR
#define BOOT_VERSION_MINOR      0u
#endif

/* USB PID used by the bootloader; the app uses 0xFE0E.  Give each product its
 * own PID if several of them are plugged into the same PC. */
#ifndef BOOT_USB_PID
#define BOOT_USB_PID            0xFE0Du
#endif

#endif /* __BOOT_INFO_H */

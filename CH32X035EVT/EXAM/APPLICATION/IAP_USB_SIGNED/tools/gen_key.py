#!/usr/bin/env python3
"""Generate a fresh random key pair for the bootloader.

    python tools/gen_key.py                 # show a fingerprint of the C file
    python tools/gen_key.py --write         # replace boot/User/img_key.c
    python tools/gen_key.py --write -o private/img_key.c

The keys never leave the generated file: all that is printed is a fingerprint,
so terminal scrollback and CI logs do not end up containing them.
"""

import argparse
import hashlib
import os
import secrets
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
DEFAULT_OUT = os.path.join(PROJ, "boot", "User", "img_key.c")

TEMPLATE = """\
/********************************** (C) COPYRIGHT *******************************
 * File Name          : {name}
 * Description        : Image authentication / encryption keys.
 *
 * GENERATED by tools/gen_key.py -- do not edit by hand.
 * Keep this file out of public repositories once it holds production keys.
 *********************************************************************************
 * Copyright (c) 2021 Nanjing Qinheng Microelectronics Co., Ltd.
 * Attention: This software (modified or not) and binary are used for
 * microcontroller manufactured by Nanjing Qinheng Microelectronics.
 *******************************************************************************/
#include "img_key.h"

const uint8_t img_hmac_key[32] = {{
{hmac}
}};

const uint8_t img_aes_key[16] = {{
{aes}
}};
"""


def _fmt(data, per_line):
    lines = []
    for i in range(0, len(data), per_line):
        row = ", ".join("0x%02x" % b for b in data[i : i + per_line])
        lines.append("    " + row)
    return ",\n".join(lines)


def _fingerprint(data):
    return hashlib.sha256(data).hexdigest()[:16]


def main(argv):
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--write", action="store_true", help="write the key file")
    ap.add_argument("-o", "--output", default=DEFAULT_OUT, help="output path")
    args = ap.parse_args(argv)

    hmac_key = secrets.token_bytes(32)
    aes_key = secrets.token_bytes(16)

    print("hmac key fingerprint: %s" % _fingerprint(hmac_key))
    print("aes  key fingerprint: %s" % _fingerprint(aes_key))

    if not args.write:
        print("\nre-run with --write to generate %s" % args.output)
        return 0

    path = os.path.abspath(args.output)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    text = TEMPLATE.format(
        name=os.path.basename(path), hmac=_fmt(hmac_key, 8), aes=_fmt(aes_key, 8)
    )
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)

    print("\nwrote %s" % path)
    print("rebuild the bootloader and re-package every image with the new keys")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

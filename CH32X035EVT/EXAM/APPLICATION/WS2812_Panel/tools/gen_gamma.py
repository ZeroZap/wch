#!/usr/bin/env python3
"""Generate the WS2812 gamma lookup table used by User/ws2812.c.

The table is a plain 256-entry uint8 LUT:

    table[i] = round(255 * (i / 255) ** gamma)

Applied to the 8-bit channel value right before it goes out to the strip, i.e.
after the global brightness scaling, so brightness stays perceptually linear.

gamma = 2.8 reproduces the curve used by the Arduino ecosystem (Adafruit's
`gamma8[]`, FastLED's default video gamma): the first 28 entries are 0 and
table[128] == 37.  Lower gamma (2.2) is the textbook sRGB value and looks a bit
brighter in the low end; 1.0 gives a linear ramp for A/B comparison.

Usage
    python gen_gamma.py                       # gamma 2.8 -> ../User/wsp_gamma.c
    python gen_gamma.py --gamma 2.2
    python gen_gamma.py --gamma 1.0 --output ../User/wsp_gamma.c
"""

import argparse
import os

HEADER = """\
/********************************** (C) COPYRIGHT *******************************
 * File Name          : wsp_gamma.c
 * Description        : 8-bit gamma table for the WS2812 output stage.
 *
 * GENERATED by tools/gen_gamma.py -- do not edit by hand.
 *   gamma = %(gamma).2f
 *   table[i] = round(255 * (i / 255) ** gamma)
 *
 * The demo applies it after the global brightness scaling, so both the
 * built-in effects and the USB frames go through the same curve.
 *********************************************************************************
 * Copyright (c) 2021 Nanjing Qinheng Microelectronics Co., Ltd.
 * Attention: This software (modified or not) and binary are used for
 * microcontroller manufactured by Nanjing Qinheng Microelectronics.
 *******************************************************************************/
#include "wsp_gamma.h"

const uint8_t ws_gamma_table[256] = {
"""

FOOTER = "};\n"


def build(gamma):
    return [int(round(255.0 * ((i / 255.0) ** gamma))) for i in range(256)]


def format_table(table):
    lines = []
    for row in range(0, 256, 16):
        chunk = table[row : row + 16]
        body = ", ".join("%3d" % v for v in chunk)
        lines.append("    %-64s /* %3d */" % (body + ",", row))
    return "\n".join(lines)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    default_out = os.path.normpath(os.path.join(here, "..", "User", "wsp_gamma.c"))

    ap = argparse.ArgumentParser(description="generate the WS2812 gamma table")
    ap.add_argument("--gamma", type=float, default=2.8)
    ap.add_argument("--output", default=default_out)
    args = ap.parse_args()

    if args.gamma <= 0:
        raise SystemExit("gamma must be > 0")

    table = build(args.gamma)
    text = HEADER % {"gamma": args.gamma} + format_table(table) + FOOTER

    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)

    first_nonzero = next(i for i, v in enumerate(table) if v)
    print("wrote %s" % args.output)
    print(
        "  gamma=%.2f  first_nonzero=%d  t[64]=%d  t[128]=%d  t[192]=%d  t[255]=%d"
        % (args.gamma, first_nonzero, table[64], table[128], table[192], table[255])
    )


if __name__ == "__main__":
    main()

CHARSET = list(GLYPHS.keys())

HEADER = """\
/********************************** (C) COPYRIGHT *******************************
 * File Name          : wsp_font.c
 * Description        : 5x7 bitmap font used by wsp_text.c.
 *
 * GENERATED by tools/gen_font.py -- do not edit by hand.
 *   %(count)d glyphs, 5 bytes each, one byte per column, bit0 = top row.
 *   wsp_font_index[] maps ASCII 32..127 to a glyph, 0xFF = not available.
 *********************************************************************************
 * Copyright (c) 2021 Nanjing Qinheng Microelectronics Co., Ltd.
 * Attention: This software (modified or not) and binary are used for
 * microcontroller manufacturer by Nanjing Qinheng Microelectronics.
 *******************************************************************************/
#include "wsp_font.h"

const uint8_t wsp_font_data[%(count)d][5] = {
"""

FOOTER = "};\n"

INDEX_HEADER = """
const uint8_t wsp_font_index[96] = {
"""


def glyph_columns(rows):
    """rows: 7 strings of 5 chars -> 5 bytes, bit0 = top row."""
    cols = []
    for x in range(5):
        value = 0
        for y in range(7):
            if rows[y][x] == "#":
                value |= 1 << y
        cols.append(value)
    return cols


def build_font():
    data = [glyph_columns(GLYPHS[ch]) for ch in CHARSET]
    index = []
    for code in range(32, 128):
        ch = chr(code)
        index.append(CHARSET.index(ch) if ch in GLYPHS else 0xFF)
    return data, index


def format_data(data):
    lines = []
    for i, cols in enumerate(data):
        body = ", ".join("0x%02X" % c for c in cols)
        lines.append("    { %-23s },  /* '%s' */" % (body, CHARSET[i]))
    return "\n".join(lines)


def format_index(index):
    lines = []
    for row in range(0, 96, 16):
        chunk = index[row : row + 16]
        body = ", ".join("0x%02X" % v for v in chunk)
        lines.append("    %-72s /* %3d */" % (body + ",", 32 + row))
    return "\n".join(lines)


def write_preview(path, scale=6):
    from PIL import Image, ImageDraw

    cols = 8
    cell_w, cell_h = 5 * scale + 4, 7 * scale + 4
    rows = (len(CHARSET) + cols - 1) // cols
    im = Image.new("RGB", (cols * cell_w, rows * cell_h), (16, 16, 16))
    d = ImageDraw.Draw(im)

    for i, ch in enumerate(CHARSET):
        data = glyph_columns(GLYPHS[ch])
        ox = (i % cols) * cell_w + 2
        oy = (i // cols) * cell_h + 2
        for x in range(5):
            for y in range(7):
                if data[x] & (1 << y):
                    d.rectangle(
                        [
                            ox + x * scale,
                            oy + y * scale,
                            ox + x * scale + scale - 1,
                            oy + y * scale + scale - 1,
                        ],
                        fill=(255, 200, 0),
                    )
    im.save(path)
    return im.size


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    default_out = os.path.normpath(os.path.join(here, "..", "User", "wsp_font.c"))

    ap = argparse.ArgumentParser(description="generate the 5x7 font")
    ap.add_argument("--output", default=default_out)
    ap.add_argument("--preview", default=None, help="also write a PNG preview")
    args = ap.parse_args()

    data, index = build_font()
    text = (
        HEADER % {"count": len(data)}
        + format_data(data)
        + FOOTER
        + INDEX_HEADER
        + format_index(index)
        + FOOTER
    )

    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%u glyphs)" % (args.output, len(data)))

    if args.preview:
        size = write_preview(args.preview)
        print("wrote %s %dx%d" % (args.preview, size[0], size[1]))


if __name__ == "__main__":
    main()

#ifndef __WSP_CONFIG_H
#define __WSP_CONFIG_H

/*---------------------------------------------------------------------------
 * Panel geometry
 *
 * The panel is built from one continuous WS2812 strip that is folded into
 * rows: row 0 goes left -> right, row 1 goes right -> left, row 2 goes
 * left -> right, and so on (serpentine / zig-zag wiring).
 *
 * Supported up to 512 pixels, i.e. 8x64 / 16x32 / 32x16 and everything in
 * between (8x8, 8x16, 8x32, 16x16 all verified).  Everything below is sized
 * from PANEL_PIXELS, so overriding these from the build system works:
 *     -DPANEL_W=16 -DPANEL_H=32
 *---------------------------------------------------------------------------*/
#ifndef PANEL_W
#define PANEL_W                 16      /* LEDs per row                  */
#endif
#ifndef PANEL_H
#define PANEL_H                 16      /* number of rows                */
#endif
#define PANEL_SERPENTINE        1       /* 1 = zig-zag, 0 = all rows L->R */
#define PANEL_START_RIGHT       0       /* 1 = first LED of row 0 is at the right end */
#define PANEL_FLIP_X            0       /* mirror horizontally           */
#define PANEL_FLIP_Y            0       /* mirror vertically             */

#define PANEL_PIXELS            (PANEL_W * PANEL_H)

/* RAM budget is measured at 32x16 (512 px); a 32x32 panel needs ~4.6KB more
 * and only just fits in the 16KB user RAM, so it is deliberately blocked. */
#if (PANEL_PIXELS > 512)
#error "PANEL_PIXELS > 512: framebuffers are sized for at most 512 px (8x64/16x32/32x16)"
#endif

/*---------------------------------------------------------------------------
 * Display modes
 *   WSP_MODE_STRIP : one linear strip, effects only (button selects effect)
 *   WSP_MODE_PANEL : serpentine panel, 2D scenes / images
 *---------------------------------------------------------------------------*/
#define WSP_MODE_PANEL          0
#define WSP_MODE_STRIP          1

#ifndef WSP_DEFAULT_MODE
#define WSP_DEFAULT_MODE        WSP_MODE_PANEL
#endif

/* number of LEDs of the linear strip (used in WSP_MODE_STRIP).
 * Defaults to the panel itself, which is the normal case: one continuous reel
 * folded into rows.  Set it explicitly for a plain linear strip. */
#ifndef STRIP_LEDS
#define STRIP_LEDS              PANEL_PIXELS
#endif

/* one framebuffer serves both modes, sized for the larger canvas */
#define CANVAS_PIXELS           ((PANEL_PIXELS > STRIP_LEDS) ? PANEL_PIXELS : STRIP_LEDS)

/*---------------------------------------------------------------------------
 * User button: PA0 active low with internal pull-up (same as EXAM/EXTI/EXTI0)
 *   short press : next effect (STRIP) / next item (PANEL)
 *   long press  : toggle STRIP <-> PANEL
 *---------------------------------------------------------------------------*/
#define WSP_BTN_ENABLE          1
#define WSP_BTN_PORT            GPIOA
#define WSP_BTN_PIN             GPIO_Pin_0
#define WSP_BTN_DEBOUNCE_MS     20
#define WSP_BTN_LONG_MS         1200

/*---------------------------------------------------------------------------
 * Segment engine (WS2812FX style)
 *---------------------------------------------------------------------------*/
#define WSP_SEG_MAX             8

/*---------------------------------------------------------------------------
 * WS2812 driver: PIOC 1-wire engine (reference: EXAM/PIOC/1_Wire)
 *
 * The WS2812 waveform is generated by the PIOC engine, the CPU only fills
 * a 3 byte/pixel buffer.  One PIOC transfer can shift up to 3072 bytes,
 * i.e. 1024 RGB pixels; keep PANEL_PIXELS <= 1024.
 *---------------------------------------------------------------------------*/
#define WS2812_BRIGHTNESS       255     /* global dimming, 0..255        */

/* Byte order sent to the strip.  Most WS2812B / SK6812 reels are GRB, older
 * WS2812 and some clones are RGB, a few are BRG.  If red comes out green (or
 * blue), change this one macro -- no other file needs to move. */
#define WS2812_ORDER_RGB        0
#define WS2812_ORDER_GRB        1
#define WS2812_ORDER_BRG        2
#define WS2812_ORDER_BGR        3
#define WS2812_ORDER_RBG        4
#define WS2812_ORDER_GBR        5

#ifndef WS2812_COLOR_ORDER
#define WS2812_COLOR_ORDER      WS2812_ORDER_GRB
#endif

/* 1 = run every channel through the gamma table (User/wsp_gamma.c) after the
 * brightness scaling, so PWM duty is perceptually linear.  Set to 0 to send
 * the raw values (useful for A/B, or to regenerate the table with
 * tools/gen_gamma.py --gamma 1.0). */
#ifndef WS2812_GAMMA
#define WS2812_GAMMA            1
#endif

/*---------------------------------------------------------------------------
 * 1-wire bit rate: PIOC clocks per WS2812 bit.  One PIOC clock is 20.83ns at
 * 48MHz, so
 *   52 -> 1.083us | 56 -> 1.167us (vendor default) | 60 -> 1.250us | 64 -> 1.333us
 * WS2812B tolerates roughly 1.1..1.4us, and the whole frame time scales with
 * this value (768 B x 8 bit x cycle x 20.83ns).  The value can be changed at
 * runtime (USB SET_CYC / CFG_SET) and is persisted in the NOR settings block.
 *---------------------------------------------------------------------------*/
#define WS2812_CYC_MIN          48      /* 1.00us */
#define WS2812_CYC_MAX          72      /* 1.50us */

#ifndef WS2812_WIRE_CYCLES
#define WS2812_WIRE_CYCLES      56
#endif

/*---------------------------------------------------------------------------
 * Frame current limit.
 *
 * A WS2812B channel draws ~20mA at full duty, so the frame current is
 *     20mA * sum(duty) / 255          (duty = the 8-bit value actually sent)
 * and 256 pixels of pure white is 256*3*255 duty -> 15.4A.
 *
 * Before every frame the canvas duty sum is compared against this budget and
 * the whole frame is dimmed proportionally when it does not fit.  Set to 0 to
 * disable (the panel then trusts whatever the supply can deliver).
 *---------------------------------------------------------------------------*/
#ifndef WSP_CURRENT_LIMIT_MA
#define WSP_CURRENT_LIMIT_MA    8000u   /* 8A */
#endif

/* resolution of the persisted copy: 1 unit = 100mA, 0 = unlimited */
#define WSP_LIMIT_UNIT_MA       100u

/*---------------------------------------------------------------------------
 * Text rendering and the frame rate / limiter badge
 *   WSP_TEXT_ENABLE  : compile the 5x7 font and wsp_text.c
 *   WSP_OSD_ENABLE   : compile the badge (needs the text module)
 *   WSP_OSD_DEFAULT  : power-on state, the USB OSD command flips it
 * On a 16x16 panel the two fps digits occupy 11 of 16 columns in row 0, so the
 * badge is off by default and meant for bring-up / USB debugging.
 *---------------------------------------------------------------------------*/
#ifndef WSP_TEXT_ENABLE
#define WSP_TEXT_ENABLE         1
#endif

#ifndef WSP_OSD_ENABLE
#define WSP_OSD_ENABLE          1
#endif

#ifndef WSP_OSD_DEFAULT
#define WSP_OSD_DEFAULT         0
#endif

/*---------------------------------------------------------------------------
 * Dithering: adds +1 to a rotating quarter of the PWM duties, which breaks up
 * the flat bands that gamma quantisation leaves in slow gradients.  Amplitude
 * is 1/255, so it is invisible per pixel but kills the posterisation.  Off by
 * default because it can only be judged by eye on the real panel.
 *---------------------------------------------------------------------------*/
#ifndef WSP_DITHER
#define WSP_DITHER              0
#endif

/* PIOC output pin:
 *   PC7 (default)  : PIOC IO0 via GPIO_Remap_PIOC, the SDI debug pins are
 *                    untouched, so WCH-Link debugging keeps working.
 *   PC18 / PC19    : PIOC IO0 / IO1 on the SDI shared pins; the init code
 *                    then calls GPIO_Remap_SWJ_Disable and SDI is lost. */
#define WS2812_PIOC_PC7         1
#define WS2812_PIOC_PC18        2
#define WS2812_PIOC_PC19        3

#ifndef WS2812_PIOC_PIN
#define WS2812_PIOC_PIN         WS2812_PIOC_PC7
#endif

/*---------------------------------------------------------------------------
 * External SPI NOR flash (W25Qxx / GD25Qxx) on SPI1 - same wiring as
 * EXAM/SPI/SPI_FLASH
 *   SCK PA5, MISO PA6, MOSI PA7, CS PA2
 *   capacity 64KB..32MB, e.g. GD25Q40 = 0xC84013 = 512KB
 *---------------------------------------------------------------------------*/
#define WSP_NOR_ENABLE          1
#define WSP_NOR_SPI_PRESCALER   SPI_BaudRatePrescaler_4     /* 48MHz / 4 = 12MHz */

/* 1 = at boot erase/program/read back the last 4KB sector (bring-up only) */
#ifndef WSP_NOR_SELFTEST
#define WSP_NOR_SELFTEST        0
#endif

/*---------------------------------------------------------------------------
 * USB CDC (PC16 = D-, PC17 = D+) - see wsp_usb.h for the packet format
 *   host -> panel : frames, brightness, NOR upload
 *   panel -> host : replies and text log lines
 * Set to 0 to build a USB-free binary (saves ~1.1KB RAM and ~4KB flash).
 *---------------------------------------------------------------------------*/
#ifndef WSP_USB_ENABLE
#define WSP_USB_ENABLE          1
#endif

/*---------------------------------------------------------------------------
 * Image player
 *   A frame of any size up to IMG_SCRATCH_PIXELS is decoded into a scratch
 *   buffer and then nearest-neighbour scaled to the panel. 16x16 needs
 *   512 bytes, 32x32 needs 2048 bytes of RAM.
 *---------------------------------------------------------------------------*/
#define IMG_SCRATCH_PIXELS      1024

/* PIOC shifts at most 3072 bytes per transfer (both modes) */
#if ((PANEL_PIXELS * 3) > 3072) || ((STRIP_LEDS * 3) > 3072)
#error "PIOC 1-wire mode supports at most 1024 RGB pixels (3072 bytes)"
#endif

/*---------------------------------------------------------------------------
 * Future: USB (CDC) frame streaming, see README.md "Roadmap"
 *---------------------------------------------------------------------------*/
#define WSP_USB_STREAM_ENABLE   0

#endif /* __WSP_CONFIG_H */

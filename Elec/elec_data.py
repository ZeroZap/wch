"""Curated electrical-characteristics data for WCH MCUs.

Every value in this file was read from the datasheet in ``Doc/DS`` and is
tagged with the datasheet page it came from.  Values that the datasheet marks
as "measured / sampled, not guaranteed" keep that wording in ``note``.

The data is intentionally kept separate from ``gen_elec.py`` so that the
extraction result can be reviewed and diffed without touching the generator.

Row helpers
-----------
LP(...)  low-power current row
WK(...)  low-power wake-up time row
OT(...)  "other" electrical row (absolute maximum, clock, reset, analog, I/O)
"""


def LP(mode, clock, condition, typ, unit, page, mn="", mx="", note=""):
    return {
        "mode": mode,
        "clock": clock,
        "condition": condition,
        "min": mn,
        "typ": typ,
        "max": mx,
        "unit": unit,
        "page": page,
        "note": note,
    }


def WK(mode, condition, typ, unit, page, mn="", mx="", note=""):
    return {
        "mode": mode,
        "condition": condition,
        "min": mn,
        "typ": typ,
        "max": mx,
        "unit": unit,
        "page": page,
        "note": note,
    }


def OT(
    category, item, symbol, condition, mn="", typ="", mx="", unit="", page="", note=""
):
    return {
        "category": category,
        "item": item,
        "symbol": symbol,
        "condition": condition,
        "min": mn,
        "typ": typ,
        "max": mx,
        "unit": unit,
        "page": page,
        "note": note,
    }


